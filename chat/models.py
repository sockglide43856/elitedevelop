class DMConversation(models.Model):
    user1 = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="dm_conversations_as_user1")
    user2 = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="dm_conversations_as_user2")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        # Ensures only one DM thread exists per pair of users
        unique_together = ('user1', 'user2')

    @classmethod
    def get_or_create_conversation(cls, u1, u2):
        """Helper to get or create a thread regardless of user ordering."""
        if u1.id > u2.id:
            u1, u2 = u2, u1
        return cls.objects.get_or_create(user1=u1, user2=u2)


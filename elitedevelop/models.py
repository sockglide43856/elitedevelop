@receiver(pre_save, sender=User)
def auto_link_existing_user_by_email(sender, instance, **kwargs):
    """
    If a new user is being created via OAuth2 with a matching email,
    prevent a new random username from being generated by pointing to
    the existing account instead.
    """
    # Only run this check if the user is new (has no primary key yet) and has an email
    if not instance.pk and instance.email:
        try:
            existing_user = User.objects.get(email__iexact=instance.email)
            # Match found! Copy over the existing user ID so Django updates
            # the existing account instead of inserting a duplicate row.
            instance.pk = existing_user.pk
            instance.username = existing_user.username
        except User.DoesNotExist:
            # No existing user found with this email; proceed with normal creation.
            pass

class UserProfile(models.Model):
    user = models.OneToOneField(User, on_delete=models.CASCADE, related_name='profile')
    current_streak = models.PositiveIntegerField(default=0)
    seconds_today = models.IntegerField(default=0)
    streak_earned_today = models.BooleanField(default=False)
    last_active_date = models.DateField(null=True, blank=True)
    about_me = models.CharField(max_length=10000, blank=True)
    proxy_requests_per_day = models.PositiveIntegerField(default=10)
    proxy_requests_today = models.PositiveIntegerField(default=0)
    proxy_requests_reset_date = models.DateField(null=True, blank=True)

    def add_active_time(self, seconds=5):
        today = timezone.now().date()

        # 1. Reset counters on a new calendar day
        if self.last_active_date != today:
            # Check if user missed yesterday (broken streak) before updating last_active_date
            if self.last_active_date and self.last_active_date < today - datetime.timedelta(days=1):
                self.current_streak = 0

            self.seconds_today = 0
            self.streak_earned_today = False
            self.last_active_date = today

        just_unlocked = False

        # 2. Increment active time until 15 minutes (900s) is reached
        if not self.streak_earned_today:
            self.seconds_today += seconds

            if self.seconds_today >= 900:
                self.streak_earned_today = True
                self.current_streak += 1
                just_unlocked = True

        self.save()
        return just_unlocked

    def __str__(self):
        return f"{self.user.username}'s Profile"

class CodeSnippet(models.Model):
    # Generates a random secure share link string (e.g., /vault/share/abc-123/)
    share_id = models.UUIDField(default=uuid.uuid4, editable=False, unique=True)
    author = models.ForeignKey(User, on_delete=models.CASCADE, related_name='snippets')
    title = models.CharField(max_length=150, default="Untitled Snippet")
    language = models.CharField(max_length=50, default="python")

    # Encrypted code block
    encrypted_code = models.TextField()
    timestamp = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-timestamp']

    def save(self, *args, **kwargs):
        if self.encrypted_code and not self.encrypted_code.startswith('gAAAAA'):
            f = Fernet(settings.FIELD_ENCRYPTION_KEY.encode())
            encrypted_bytes = f.encrypt(self.encrypted_code.encode())
            self.encrypted_code = encrypted_bytes.decode()
        super().save(*args, **kwargs)

    @property
    def get_decrypted_code(self):
        try:
            f = Fernet(settings.FIELD_ENCRYPTION_KEY.encode())
            decrypted_bytes = f.decrypt(self.encrypted_code.encode())
            return decrypted_bytes.decode()
        except Exception:
            return "// Error: Code asset decryption failed."
